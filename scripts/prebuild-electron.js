// Build an Electron prebuild for opencv4nodejs without the unpublished
// @nut-tree/opencv-build-<platform> packages.
//
// Required env:
//   ELECTRON_TARGET   e.g. 25.9.8
// Optional env:
//   OPENCV_DIR        Windows only: e.g. C:\opencv\opencv\build
//   OPENCV_PREFIX     macOS only: brew prefix (auto-detected by default)
//   GH_TOKEN          GitHub token, only used when IS_TAG=true
//   IS_TAG            "true" to upload the prebuild to the matching GitHub release
//
// Linux / macOS link against the system OpenCV (apt / brew), matching how the
// original opencv4nodejs-prebuilt packages behaved. Windows bundles the
// OpenCV DLLs inside the prebuild archive.
const fs = require("fs");
const path = require("path");
const { execFileSync, spawnSync } = require("child_process");

const cwd = process.cwd();
const platform = process.platform;
const isWin = platform === "win32";
const electronTarget = process.env.ELECTRON_TARGET || "25.9.8";
const isTag = process.env.IS_TAG === "true";
const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;

function fail(msg) {
  console.error("[opencv-prebuilt] " + msg);
  process.exit(1);
}

function log(msg) {
  console.log("[opencv-prebuilt] " + msg);
}

function existingDir(dirs) {
  return dirs.find((d) => d && fs.existsSync(d));
}

// --- locate OpenCV and build the gyp env -------------------------------
let includeDir;
let defines = [];
let libraries = [];
let opencvLibDir = null;
let opencvBinDir = null;

if (isWin) {
  const opencvRoot = process.env.OPENCV_DIR || "C:\\opencv\\opencv\\build";
  includeDir = path.join(opencvRoot, "include");
  if (!fs.existsSync(path.join(includeDir, "opencv2", "opencv.hpp"))) {
    fail("OpenCV headers not found in " + includeDir);
  }

  const x64Dir = path.join(opencvRoot, "x64");
  if (!fs.existsSync(x64Dir)) fail("OpenCV x64 dir not found: " + x64Dir);
  const toolsetDirs = fs
    .readdirSync(x64Dir)
    .filter((d) => fs.existsSync(path.join(x64Dir, d, "lib")));
  if (!toolsetDirs.length) fail("no OpenCV lib dir under " + x64Dir);
  toolsetDirs.sort();
  opencvLibDir = path.join(x64Dir, toolsetDirs[toolsetDirs.length - 1], "lib");
  opencvBinDir = path.join(path.dirname(opencvLibDir), "bin");

  // ignore debug (*d.lib) libraries shipped next to the release ones
  const libFiles = fs
    .readdirSync(opencvLibDir)
    .filter((f) => /^opencv_.*\.lib$/i.test(f) && !/d\.lib$/i.test(f));
  if (!libFiles.length) fail("no opencv_*.lib found in " + opencvLibDir);

  // Prefer the world library when present: one import lib for every module.
  const worldLib = libFiles.find((f) => /^opencv_world.*\.lib$/i.test(f));
  if (worldLib) {
    libraries = [path.join(opencvLibDir, worldLib)];
    log("using world library: " + worldLib);
    // Module availability for OpenCV >= 3.2 comes from
    // <opencv2/opencv_modules.hpp>, generated by the OpenCV build itself.
  } else {
    libraries = libFiles.map((f) => path.join(opencvLibDir, f));
    defines = libFiles.map(
      (f) =>
        "OPENCV4NODEJS_FOUND_LIBRARY_" +
        f
          .replace(/^opencv_/i, "")
          .replace(/[0-9]+\.lib$/i, "")
          .toUpperCase()
    );
    log("using module libraries: " + libFiles.join(", "));
  }
} else if (platform === "darwin") {
  const prefix =
    process.env.OPENCV_PREFIX ||
    (fs.existsSync("/opt/homebrew") ? "/opt/homebrew" : "/usr/local");
  includeDir = existingDir([
    path.join(prefix, "include", "opencv4"),
    path.join(prefix, "include"),
  ]);
  opencvLibDir = existingDir([
    path.join(prefix, "lib"),
    "/usr/local/lib",
    "/opt/homebrew/lib",
  ]);
  if (!includeDir) fail("OpenCV headers not found under " + prefix);
  if (!opencvLibDir) fail("OpenCV lib dir not found under " + prefix);

  const libs = fs
    .readdirSync(opencvLibDir)
    .filter((f) => /^libopencv_[a-z0-9]+\.dylib$/i.test(f));
  if (!libs.length) fail("no libopencv_*.dylib found in " + opencvLibDir);
  libraries = ["-L" + opencvLibDir, "-Wl,-rpath," + opencvLibDir].concat(
    libs.map((f) => "-l" + f.replace(/^lib/, "").replace(/\.dylib$/i, ""))
  );
  log("using " + libs.length + " dylibs from " + opencvLibDir);
} else {
  includeDir = existingDir(["/usr/include/opencv4", "/usr/include"]);
  if (!includeDir) fail("OpenCV headers not found (install libopencv-dev)");

  try {
    opencvLibDir = execFileSync("pkg-config", ["--variable=libdir", "opencv4"], {
      encoding: "utf-8",
    }).trim();
  } catch (e) {
    opencvLibDir = existingDir([
      "/usr/lib/x86_64-linux-gnu",
      "/usr/lib/aarch64-linux-gnu",
      "/usr/lib",
      "/usr/local/lib",
    ]);
  }
  if (!opencvLibDir || !fs.existsSync(opencvLibDir)) {
    fail("OpenCV lib dir not found");
  }

  const libs = fs
    .readdirSync(opencvLibDir)
    .filter((f) => /^libopencv_[a-z0-9]+\.so$/i.test(f));
  if (!libs.length) fail("no libopencv_*.so found in " + opencvLibDir);
  libraries = ["-L" + opencvLibDir].concat(
    libs.map((f) => "-l" + f.replace(/^lib/, "").replace(/\.so$/i, ""))
  );
  log("using " + libs.length + " shared libs from " + opencvLibDir);
}

log("OpenCV include dir: " + includeDir);

// --- stage runtime DLLs next to the binding (Windows only) --------------
const releaseDir = path.join(cwd, "build", "Release");
fs.mkdirSync(releaseDir, { recursive: true });

if (isWin && opencvBinDir) {
  const dllFiles = fs.readdirSync(opencvBinDir).filter((f) => /\.dll$/i.test(f));
  const world = libraries.some((l) => /opencv_world/i.test(l));
  let copied = 0;
  for (const f of dllFiles) {
    if (/d\.dll$/i.test(f)) continue; // debug build
    if (world) {
      // world build: copy the world dll and the ffmpeg plugin, nothing else
      if (!/opencv_world|videoio_ffmpeg/i.test(f)) continue;
    } else if (/^opencv_world/i.test(f)) {
      continue;
    }
    fs.copyFileSync(path.join(opencvBinDir, f), path.join(releaseDir, f));
    copied++;
  }
  log("copied " + copied + " OpenCV dll(s) into build/Release");
}

// --- run prebuild -------------------------------------------------------
const prebuildBin = require.resolve("prebuild/bin.js");
const args = [
  prebuildBin,
  "--runtime=electron",
  "--target=" + electronTarget,
  "--arch=" + process.arch,
  "--include-regex=\\.(node|dll|dylib|so)$",
  "--verbose",
];
if (isTag && token) {
  args.push("-u", token);
}

// gyp `<!@(...)` output is whitespace/escape parsed; backslash paths from
// path.join() get mangled, so always feed forward slashes.
const toGypPath = (p) => p.replace(/\\/g, "/");

log("running: node " + args.join(" "));
const res = spawnSync(process.execPath, args, {
  cwd,
  stdio: "inherit",
  env: Object.assign({}, process.env, {
    OPENCV4NODEJS_DEFINES: defines.join("\n"),
    OPENCV4NODEJS_INCLUDES: toGypPath(includeDir),
    OPENCV4NODEJS_LIBRARIES: libraries.map(toGypPath).join("\n"),
  }),
});

if (res.error) fail(res.error.message);
if (res.status !== 0) fail("prebuild exited with code " + res.status);

for (const f of fs.readdirSync(releaseDir)) {
  const p = path.join(releaseDir, f);
  log("built: " + f + " (" + fs.statSync(p).size + " bytes)");
}
